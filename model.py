import torch

def softmax_attention_weights(masked_scores):
    # TODO: softmax over the last axis, zeroing rows that are entirely -inf
    P = torch.softmax(masked_scores, dim=-1)
    P = torch.nan_to_num(P, nan=0.0)
    return P

